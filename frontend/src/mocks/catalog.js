function tomorrowDate()         {
  const d = new Date();
  d.setDate(d.getDate() + 1);
  return d.toISOString().slice(0, 10);
}

function buildPickupDates(
  marketId        ,
  marketName        ,
  stallLabel        ,
  latitude        ,
  longitude        ,
  slotIdBase        ,
)               {
  const date = tomorrowDate();
  const day = ((new Date(date + 'T12:00:00').getDay() + 6) % 7) + 1;
  const day_of_week = day             ;
  return {
    market_id: marketId,
    market_name: marketName,
    stall_label: stallLabel,
    latitude,
    longitude,
    dates: [
      {
        date,
        day_of_week,
        slots: [
          {
            pickup_slot_id: slotIdBase,
            start_time: '08:00',
            end_time: '09:00',
            cutoff_at: new Date(Date.now() + 12 * 3600_000).toISOString(),
            is_bookable: true,
          },
          {
            pickup_slot_id: slotIdBase + 1,
            start_time: '09:00',
            end_time: '10:00',
            cutoff_at: new Date(Date.now() + 12 * 3600_000).toISOString(),
            is_bookable: true,
          },
        ],
      },
    ],
  };
}

